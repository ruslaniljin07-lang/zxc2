# По ключу (тема + язык) — (для чего, где используется).
# Ключ строится как '<язык>:<тема в нижнем регистре>'.
WHY = {}
WHERE = {}


def put(lang, topic, why, where):
    key = (lang, topic.strip().lower())
    WHY[key] = why
    WHERE[key] = where


# ------------------------- общие концепции --------------------------------
def put_common(lang, topics, why, where):
    for topic in topics:
        put(lang, topic, why, where)


