# ------------------------- применение к файлам ----------------------------
total = 0
missing = []

for filename in sorted(os.listdir(LANG_DIR)):
    if not filename.endswith('.json'):
        continue
    code = filename[:-5]
    path = os.path.join(LANG_DIR, filename)
    with open(path, encoding='utf-8') as f:
        raw = json.load(f)

    data = raw.get(code, raw)
    changed = False

    for sheet in data.get('cheatsheets', []):
        key = (code, str(sheet.get('title', '')).strip().lower())
        why = WHY.get(key)
        where = WHERE.get(key)
        if why:
            sheet['why'] = why
        if where:
            sheet['where'] = where
        if why or where:
            changed = True
            total += 1
        else:
            missing.append('%s: %s' % (code, sheet.get('title', '?')))

    if changed:
        with open(path, 'w', encoding='utf-8', newline='') as f:
            json.dump({code: data}, f, ensure_ascii=False, indent=1)

print('шпаргалок с пояснениями: %d' % total)
if missing:
    print('БЕЗ ПОЯСНЕНИЯ (%d):' % len(missing))
    for item in missing:
        print('  - ' + item)


