def apply_explanations(lang):
    """Дописывает explain вопросам уроков, где его не было."""
    path = os.path.join(LANG_DIR, lang + '.json')
    with open(path, encoding='utf-8') as f:
        raw = json.load(f)
    data = raw.get(lang, raw)

    added = 0
    missing = []
    for module in data['modules']:
        for lesson in module['lessons']:
            for quest in lesson.get('test') or []:
                if (quest.get('explain') or '').strip():
                    continue
                text = (SPECIFIC.get(lang, {}).get(quest['question'])
                        or SHARED.get(quest['question']))
                if not text:
                    missing.append(f'{lang}: {quest["question"]}')
                    continue
                quest['explain'] = text
                added += 1
    if missing:
        raise SystemExit('нет пояснений: ' + '; '.join(missing))

    with open(path, 'w', encoding='utf-8') as f:
        json.dump({lang: data}, f, ensure_ascii=False, indent=1)
    print(f'{lang:11} добавлено пояснений: {added}')


for _lang in LANGS:
    apply_explanations(_lang)
