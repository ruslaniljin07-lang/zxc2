def lesson(lid, title, desc, theory, examples, tasks, tests, cheat,
           xp=15, difficulty='easy'):
    return {
        'id': lid,
        'title': title,
        'description': desc,
        'xp_reward': xp,
        'difficulty': difficulty,
        'theory': theory,
        'examples': examples,
        'tasks': tasks,
        'test': tests,
        'cheatsheet': cheat,
    }


def task(tid, title, desc, diff, initial, check, hints, solution):
    return {
        'id': tid,
        'title': title,
        'description': desc,
        'difficulty': diff,
        'initial_code': initial,
        'check': check,
        'hints': hints,
        'solution': solution,
    }


def pcheck(test_code):
    """Проверка для Python — исполняемый assert."""
    return {'type': 'python', 'test_code': test_code}


def ccheck(require, reject=None):
    """Проверка для JS/Java/C++ — проверка конструкций в коде."""
    check = {'type': 'contains', 'require': require}
    if reject:
        check['reject'] = reject
    return check


def q(question, options, correct):
    return {'question': question, 'options': options, 'correct': correct}
