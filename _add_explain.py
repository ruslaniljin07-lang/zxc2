def apply_explanations(lang):
    """Дописывает explain вопросам уроков, где его не было."""
    path = os.path.join(LANG_DIR, lang + '.json')
    with open(path, encoding='utf-8') as f:
        raw = json.load(f)
    data = raw.get(lang, raw)
    planned = EXPLAIN[lang]

    added = 0
    missing = []
    for module in data['modules']:
        for lesson in module['lessons']:
            questions = lesson.get('test') or []
            texts = planned.get(lesson['id'])
            for i, quest in enumerate(questions):
                if (quest.get('explain') or '').strip():
                    continue
                if texts and i < len(texts):
                    quest['explain'] = texts[i]
                    added += 1
                else:
                    missing.append(f'урок {lesson["id"]} вопрос {i + 1}')
    if missing:
        raise SystemExit(f'{lang}: нет пояснений для {missing}')

    with open(path, 'w', encoding='utf-8') as f:
        json.dump({lang: data}, f, ensure_ascii=False, indent=2)
    print(f'{lang:11} добавлено пояснений: {added}')


for _lang in ['python', 'javascript', 'java', 'cpp']:
    apply_explanations(_lang)
